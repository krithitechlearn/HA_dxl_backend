-- Create Roles
CREATE ROLE ADMIN_ROLE;
CREATE ROLE USER_ROLE;
CREATE ROLE GUEST_ROLE;
CREATE ROLE SYSTEM_ROLE;

-- Grant basic connection and schema usage
GRANT CONNECT ON DATABASE ha_dxl TO ADMIN_ROLE, USER_ROLE, GUEST_ROLE, SYSTEM_ROLE;
GRANT USAGE ON SCHEMA public TO ADMIN_ROLE, USER_ROLE, GUEST_ROLE, SYSTEM_ROLE;

-- ADMIN_ROLE grants
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO ADMIN_ROLE;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO ADMIN_ROLE;
GRANT ALL PRIVILEGES ON ALL FUNCTIONS IN SCHEMA public TO ADMIN_ROLE;

-- USER_ROLE grants
GRANT SELECT, UPDATE ON users TO USER_ROLE;
GRANT SELECT ON rooms TO USER_ROLE;
GRANT SELECT, UPDATE ON devices TO USER_ROLE;
GRANT INSERT ON device_commands TO USER_ROLE;
GRANT SELECT ON device_commands TO USER_ROLE;
GRANT SELECT ON telemetry TO USER_ROLE;
GRANT ALL PRIVILEGES ON automation_rules TO USER_ROLE;
GRANT ALL PRIVILEGES ON automation_actions TO USER_ROLE;
GRANT SELECT ON automation_execution_logs TO USER_ROLE;
GRANT SELECT ON user_device_access TO USER_ROLE;

-- GUEST_ROLE grants
GRANT SELECT ON rooms TO GUEST_ROLE;
GRANT SELECT ON devices TO GUEST_ROLE;
GRANT INSERT ON device_commands TO GUEST_ROLE;
GRANT SELECT ON device_commands TO GUEST_ROLE;
GRANT SELECT ON telemetry TO GUEST_ROLE;
GRANT SELECT ON user_device_access TO GUEST_ROLE;

-- SYSTEM_ROLE grants
GRANT INSERT ON telemetry TO SYSTEM_ROLE;
GRANT UPDATE (last_seen_at, status) ON devices TO SYSTEM_ROLE;
GRANT INSERT ON audit_logs TO SYSTEM_ROLE;
